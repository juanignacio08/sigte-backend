CREATE TABLE maestros.plantilla_documento (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escuela_id            BIGINT       NOT NULL,
    tipo_documento_codigo VARCHAR(6)   NOT NULL,
    nombre_documento      VARCHAR(250) NOT NULL,
    archivo_url           TEXT         NOT NULL,
    plazo_dias            INT          NULL,
    plazo_meses           INT          NULL,
    estado                INT          NOT NULL DEFAULT 1,
    creado_por            VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_creacion        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por       VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_actualizacion   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    eliminado             BOOLEAN      NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_plantilla_escuela FOREIGN KEY (escuela_id)
        REFERENCES maestros.escuela (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX uk_plantilla_escuela_tipo
    ON maestros.plantilla_documento (escuela_id, tipo_documento_codigo)
    WHERE estado = 1;

CREATE INDEX idx_plantilla_escuela ON maestros.plantilla_documento(escuela_id);
CREATE INDEX idx_plantilla_tipo    ON maestros.plantilla_documento(tipo_documento_codigo);

