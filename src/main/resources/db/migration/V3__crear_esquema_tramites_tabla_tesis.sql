-- =====================================================
-- 2. TABLA: tramites.tesis_autor (Autores de la Tesis)
-- =====================================================
CREATE TABLE tramites.tesis_autor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tesis_id UUID NOT NULL,
    estudiante_id BIGINT NOT NULL,
    fecha_asociacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Campos de auditoría
    estado INT NOT NULL DEFAULT 1,
    creado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_actualizacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,

    -- Restricciones de Clave Foránea y Unicidad
    CONSTRAINT fk_tesis_autor_tesis FOREIGN KEY (tesis_id)
        REFERENCES tramites.tesis (id) ON DELETE CASCADE,
    CONSTRAINT fk_tesis_autor_estudiante FOREIGN KEY (estudiante_id)
        REFERENCES personas.estudiante (id) ON DELETE RESTRICT,
    CONSTRAINT uk_tesis_estudiante UNIQUE (tesis_id, estudiante_id)
);

-- Índices de rendimiento
CREATE INDEX idx_tesis_autor_tesis ON tramites.tesis_autor(tesis_id);
CREATE INDEX idx_tesis_autor_estudiante ON tramites.tesis_autor(estudiante_id);


-- =====================================================
-- 3. TABLA: tramites.expediente_tesis (Historial de Expedientes Externos)
-- =====================================================
CREATE TABLE tramites.expediente_tesis (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tesis_id UUID NOT NULL,
    numero_expediente VARCHAR(50) NOT NULL,
    etapa_codigo VARCHAR(6) NOT NULL,
    numero_revision INT NOT NULL DEFAULT 1,
    fecha_ingreso TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo_baja VARCHAR(250),
    estado INT NOT NULL DEFAULT 1,
    creado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_actualizacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_expediente_tesis FOREIGN KEY (tesis_id)
        REFERENCES tramites.tesis (id) ON DELETE CASCADE,
    CONSTRAINT uk_expediente_numero UNIQUE (numero_expediente)
);

-- Índice de rendimiento
CREATE INDEX idx_expediente_tesis_id ON tramites.expediente_tesis(tesis_id);

