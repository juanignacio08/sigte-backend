CREATE TABLE tramites.comision (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tesis_id            UUID    NOT NULL,
    etapa_codigo        VARCHAR(6) NOT NULL,
    fecha_conformacion  DATE    NOT NULL DEFAULT CURRENT_DATE,

    estado INT NOT NULL DEFAULT 1,
    creado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_actualizacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,

    -- Restricciones
    CONSTRAINT fk_comision_tesis FOREIGN KEY (tesis_id)
        REFERENCES tramites.tesis (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX uk_comision_tesis_etapa
    ON tramites.comision (tesis_id, etapa_codigo)
    WHERE eliminado = FALSE;

CREATE INDEX idx_comision_tesis_id    ON tramites.comision(tesis_id);
CREATE INDEX idx_comision_etapa       ON tramites.comision(etapa_codigo);


CREATE TABLE tramites.comision_miembro (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comision_id     BIGINT NOT NULL,
    docente_id      BIGINT NOT NULL,
    rol_codigo      VARCHAR(6) NOT NULL,
    orden           INT NOT NULL DEFAULT 1,
    fecha_alta      DATE NOT NULL DEFAULT CURRENT_DATE,
    fecha_baja      DATE NULL,
    motivo_baja     VARCHAR(250),

    estado INT NOT NULL DEFAULT 1,
    creado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_actualizacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_cm_comision FOREIGN KEY (comision_id)
        REFERENCES tramites.comision (id) ON DELETE CASCADE,
    CONSTRAINT fk_cm_docente FOREIGN KEY (docente_id)
        REFERENCES personas.docente (id) ON DELETE RESTRICT
);

-- Un mismo docente no puede tener 2 roles vigentes en la misma comisión
CREATE UNIQUE INDEX uk_cm_docente_vigente
    ON tramites.comision_miembro (comision_id, docente_id)
    WHERE eliminado = FALSE;

CREATE INDEX idx_cm_comision  ON tramites.comision_miembro(comision_id);
CREATE INDEX idx_cm_docente   ON tramites.comision_miembro(docente_id);
CREATE INDEX idx_cm_rol       ON tramites.comision_miembro(rol_codigo);


