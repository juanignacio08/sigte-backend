-- =====================================================
-- ESQUEMA: personas
-- =====================================================
CREATE SCHEMA IF NOT EXISTS personas;

-- 1. Tabla: docente
CREATE TABLE personas.docente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(10) NULL,
    escuela_id BIGINT NOT NULL,
    departamento_academico_id BIGINT NOT NULL,
    tipo_documento_codigo VARCHAR(6) NULL,
    numero_documento VARCHAR(15) NULL,
    nombres VARCHAR(100) NOT NULL,
    primer_apellido VARCHAR(100) NOT NULL,
    segundo_apellido VARCHAR(100) NOT NULL,
    correo_institucional VARCHAR(100) NOT NULL,
    genero_codigo VARCHAR(6) NOT NULL,
    telefono VARCHAR(15),

    -- Campos de auditoría
    estado INT NOT NULL DEFAULT 1,
    creado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_actualizacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,

    -- Restricciones
    CONSTRAINT fk_docente_escuela FOREIGN KEY (escuela_id)
        REFERENCES maestros.escuela (id) ON DELETE RESTRICT,
    CONSTRAINT fk_docente_departamento FOREIGN KEY (departamento_academico_id)
        REFERENCES maestros.departamento_academico (id) ON DELETE RESTRICT,
    CONSTRAINT uk_docente_documento UNIQUE (tipo_documento_codigo, numero_documento),
    CONSTRAINT uk_docente_correo UNIQUE (correo_institucional)
);

-- Índices de rendimiento
CREATE INDEX idx_docente_escuela ON personas.docente(escuela_id);
CREATE INDEX idx_docente_departamento ON personas.docente(departamento_academico_id);