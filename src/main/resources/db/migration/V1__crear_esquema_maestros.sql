-- Crear esquema para tablas maestras
CREATE SCHEMA IF NOT EXISTS maestros;

-- 1. Tabla: facultad
CREATE TABLE maestros.facultad (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    abreviatura VARCHAR(10) NOT NULL,
    denominacion VARCHAR(200) NOT NULL,
    estado INT NOT NULL DEFAULT 1,
    creado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_actualizacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE
);

-- 2. Tabla: departamento_academico
CREATE TABLE maestros.departamento_academico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facultad_id BIGINT NOT NULL,
    abreviatura VARCHAR(10) NOT NULL,
    denominacion VARCHAR(200) NOT NULL,
    estado INT NOT NULL DEFAULT 1,
    creado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_actualizacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_departamento_facultad FOREIGN KEY (facultad_id)
        REFERENCES maestros.facultad (id) ON DELETE RESTRICT
);

-- 3. Tabla: escuela
CREATE TABLE maestros.escuela (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    departamento_academico_id BIGINT NOT NULL,
    codigo INT NOT NULL,
    abreviatura VARCHAR(10) NOT NULL,
    denominacion VARCHAR(200) NOT NULL,
    plantilla_memorando TEXT,
    plantilla_resolucion TEXT,
    estado INT NOT NULL DEFAULT 1,
    creado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_actualizacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_escuela_departamento FOREIGN KEY (departamento_academico_id)
        REFERENCES maestros.departamento_academico (id) ON DELETE RESTRICT
);

CREATE INDEX idx_escuela_departamento_id ON maestros.escuela(departamento_academico_id);


