CREATE TABLE tramites.envio_correo (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expediente_id        BIGINT NOT NULL,
    asunto              VARCHAR(300) NOT NULL,
    cuerpo              TEXT NULL,
    destinatarios       JSONB NOT NULL DEFAULT '[]'::jsonb,
    adjuntos            JSONB NOT NULL DEFAULT '[]'::jsonb,
    fecha_envio         TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    error_mensaje       TEXT NULL,

    estado                  INT          NOT NULL DEFAULT 1,
    creado_por              VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_creacion          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por         VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_actualizacion     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    eliminado               BOOLEAN      NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_envio_doc FOREIGN KEY (expediente_id)
        REFERENCES tramites.expediente_tesis (id) ON DELETE CASCADE
);

CREATE INDEX idx_envio_documento ON tramites.envio_correo(expediente_id);