-- =====================================================
-- ESQUEMA: tramites (Módulo Operativo de Tesis)
-- =====================================================
CREATE SCHEMA IF NOT EXISTS tramites;

-- Activar extensión para generación de UUIDs
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. Tabla: tesis
CREATE TABLE tramites.tesis (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    escuela_id BIGINT NOT NULL,
    titulo TEXT NOT NULL,
    titulo_dictaminado TEXT NULL,
    estado_codigo VARCHAR(6) NOT NULL DEFAULT '003001',
    fecha_registro TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Campos de auditoría
    estado INT NOT NULL DEFAULT 1,
    creado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_actualizacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,

    -- Restricciones
    CONSTRAINT fk_tesis_escuela FOREIGN KEY (escuela_id)
        REFERENCES maestros.escuela (id) ON DELETE RESTRICT
);

-- Índice de rendimiento
CREATE INDEX idx_tesis_escuela ON tramites.tesis(escuela_id);


