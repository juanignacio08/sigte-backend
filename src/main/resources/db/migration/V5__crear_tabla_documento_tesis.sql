-- =====================================================================
-- TABLA: tramites.documento_tesis
-- Almacena todos los documentos generados o recibidos de un expediente:
-- memorandos, dictámenes, resoluciones y actas.
-- =====================================================================
CREATE TABLE tramites.documento_tesis (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tesis_id                UUID         NOT NULL,
    expediente_tesis_id     BIGINT       NULL,
    tipo_documento_codigo   VARCHAR(6)   NOT NULL,
    numero_correlativo      INT          NULL,
    anio_correlativo        INT          NULL,
    fecha_emision           DATE         NOT NULL DEFAULT CURRENT_DATE,
    archivo_word_url        TEXT         NULL,
    archivo_pdf_url         TEXT         NULL,
    tamanio_bytes_word      BIGINT       NULL,
    tamanio_bytes_pdf       BIGINT       NULL,
    resultado_codigo        VARCHAR(6)   NULL,
    observaciones           TEXT         NULL,
    estado_codigo           VARCHAR(6)   NOT NULL DEFAULT '009001',

    estado                  INT          NOT NULL DEFAULT 1,
    creado_por              VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_creacion          TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por         VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_actualizacion     TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    eliminado               BOOLEAN      NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_doc_tesis FOREIGN KEY (tesis_id)
        REFERENCES tramites.tesis (id) ON DELETE CASCADE,
    CONSTRAINT fk_doc_expediente FOREIGN KEY (expediente_tesis_id)
        REFERENCES tramites.expediente_tesis (id) ON DELETE SET NULL
);

-- ---------------------------------------------------------------------
-- Índices y restricciones
-- ---------------------------------------------------------------------

-- Un correlativo único por tipo y año (solo cuando tiene número asignado)
CREATE UNIQUE INDEX uk_doc_correlativo
    ON tramites.documento_tesis (tipo_documento_codigo, anio_correlativo, numero_correlativo)
    WHERE numero_correlativo IS NOT NULL
      AND eliminado = FALSE;

-- Búsquedas frecuentes
CREATE INDEX idx_doc_tesis          ON tramites.documento_tesis(tesis_id);
CREATE INDEX idx_doc_expediente     ON tramites.documento_tesis(expediente_tesis_id);
CREATE INDEX idx_doc_tipo           ON tramites.documento_tesis(tipo_documento_codigo);
CREATE INDEX idx_doc_estado         ON tramites.documento_tesis(estado_codigo);
CREATE INDEX idx_doc_fecha_emision  ON tramites.documento_tesis(fecha_emision DESC);