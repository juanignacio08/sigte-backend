-- 4. Tabla: maestro (Agrupadores e Ítems Auxiliares)
CREATE TABLE maestros.maestro (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_tabla VARCHAR(3) NOT NULL,
    codigo_item VARCHAR(3) NOT NULL,
    codigo VARCHAR(6) NOT NULL, -- Formato '001000' para agrupador, '001001' para ítem
    denominacion VARCHAR(200) NOT NULL,
    es_sistema BOOLEAN NOT NULL DEFAULT TRUE, -- Si es TRUE, el agrupador/ítem no se borra

    -- Campos de auditoría
    estado INT NOT NULL DEFAULT 1,
    creado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_actualizacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX idx_maestro_codigo_tabla ON maestros.maestro(codigo_tabla);
CREATE INDEX idx_maestro_codigo_item ON maestros.maestro(codigo_item);

