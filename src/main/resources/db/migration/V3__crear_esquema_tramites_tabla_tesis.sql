-- =====================================================
-- 4. TABLA: tramites.expediente_archivo (Almacena los pdf enviados en un expediente)
-- =====================================================
CREATE TABLE tramites.expediente_archivo (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expediente_tesis_id BIGINT NOT NULL,
    nombre_archivo VARCHAR(255) NOT NULL,
    archivo_url TEXT NOT NULL,
    tamanio_bytes BIGINT NULL,

    estado INT NOT NULL DEFAULT 1,
    creado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_creacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    actualizado_por VARCHAR(100) NOT NULL DEFAULT 'admin',
    fecha_actualizacion TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_expediente_archivo_expediente FOREIGN KEY (expediente_tesis_id)
        REFERENCES tramites.expediente_tesis (id) ON DELETE CASCADE
);

CREATE INDEX idx_expediente_archivo_expediente ON tramites.expediente_archivo(expediente_tesis_id);
